import * as fs from "node:fs";
import * as path from "node:path";

const ROOT = path.join(import.meta.dirname, '../..');
const BUILD_JSON = path.join(ROOT, 'build.json');
const DATA_PATH = path.join(ROOT, 'plugins', 'Assets', '_DATA_BASE');
const LOCALIZATION_OUTPUT = path.join(DATA_PATH, 'LocalizationGenerated.ts');


(async () => {
    // Ensure output directory exists
    if (!fs.existsSync(DATA_PATH)) {
        fs.mkdirSync(DATA_PATH, { recursive: true });
    }

    // 1. Read build.json and extract localization data
    let localizationData: Record<string, Record<string, string>> = {};
    let keys: string[] = [];
    
    try {
        let buildJsonContent = fs.readFileSync(BUILD_JSON, 'utf-8');
        // Strip JSON comments (// and /* */)
        buildJsonContent = buildJsonContent
            .replace(/\/\/.*$/gm, '')
            .replace(/\/\*[\s\S]*?\*\//g, '');
        
        const buildConfig = JSON.parse(buildJsonContent);
        
        // Handle nested LOCALIZATION (some configs have LOCALIZATION inside LOCALIZATION)
        let loc = buildConfig.LOCALIZATION;
        
        // If LOCALIZATION doesn't have language codes as direct keys, check for nested LOCALIZATION
        if (loc && typeof loc === 'object') {
            const locKeys = Object.keys(loc);
            const hasLangKeys = locKeys.some(k => k.length === 2); // simple check for language codes like EN, FR
            if (!hasLangKeys && 'LOCALIZATION' in loc) {
                loc = (loc as any).LOCALIZATION;
            }
        }
        
        localizationData = loc || {};
        
        // Extract all unique keys from all languages
        const allKeys = new Set<string>();
        for (const lang of Object.keys(localizationData)) {
            const langData = localizationData[lang];
            if (langData && typeof langData === 'object') {
                for (const key of Object.keys(langData)) {
                    allKeys.add(key);
                }
            }
        }
        keys = Array.from(allKeys).sort();
        
    } catch (e: any) {
        console.warn('| Warning: Could not read build.json:', e.message);
        console.log('| No localization data found.');
        return;
    }

    if (keys.length === 0) {
        console.log('| No localization keys found in build.json');
        console.log('| Add keys to build.json -> LOCALIZATION -> EN (or any language)');
        return;
    }

    // 2. Generate the output file
    const output = generateLocalizationFile(keys, localizationData);
    fs.writeFileSync(LOCALIZATION_OUTPUT, output);

    console.log('|');
    console.log('| Localization generated!');
    console.log(`| Output: ${LOCALIZATION_OUTPUT}`);
    console.log(`| Keys generated in LocalKey enum: ${keys.length}`);
    console.log(`| Languages: ${Object.keys(localizationData).join(', ')}`);
    console.log('|');
    console.log('| Keys:');
    keys.forEach(key => console.log(`|   - ${key}`));
    console.log('|');
    console.log('| Next steps:');
    console.log('| 1. Add translation values to build.json -> LOCALIZATION');
    console.log('| 2. Run: npm run loc');
    console.log('|');
})();


function generateLocalizationFile(keys: string[], localizationData: Record<string, Record<string, string>>): string {
    const languages = Object.keys(localizationData);
    
    // Generate LocalKey enum from keys
    const enumValues = keys.map(k => `    ${k} = "${k}"`).join(',\n');

    return `// =====================================================
// AUTO-GENERATED FILE - DO NOT EDIT MANUALLY
// Generated by: plugins/Assets/localization_generate.ts
// Source: build.json -> LOCALIZATION
// =====================================================

// LocalKey enum (auto-generated from build.json LOCALIZATION keys)
export enum LocalKey {
${enumValues}
}

// Localization data from build.json
export const LOCALIZATION_DATA = ${JSON.stringify(localizationData, null, 2)};

// =====================================================
// HOW TO USE:
// =====================================================
// 
// In your code, import and use:
//
//   import { LocalKey, GetLocal } from './BUILD/Localization';
//   
//   this.title = new PIXI.Text(GetLocal(LocalKey.title), { ... });
//
// The GetLocal function requires:
// - LOCALIZATION (global object with localization strings)
// - LANGUAGE (global string with current language)
//
// These are injected at build time via webpack defines.
// =====================================================
`;
}
